#pragma once
#include <fast_livo2/config.h>
namespace fast_livo2::adapter {
struct NodeConfig {
  Config core;
  std::string lid_topic = "/livox/lidar", imu_topic = "/livox/imu", img_topic = "/left_camera/image";
  std::string world_frame = "camera_init", body_frame = "body";
};
// A single catalog binds the native ROS parameter APIs.
template<class Reader, class CameraReader>
NodeConfig readConfig(Reader &&read, CameraReader &&camera_read) {
  NodeConfig node;
  auto &config = node.core;
  read("common.lid_topic", node.lid_topic);
  read("common.imu_topic", node.imu_topic);
  read("common.ros_driver_bug_fix", config.ros_driver_fix_en);
  read("common.img_en", config.img_en);
  read("common.lidar_en", config.lidar_en);
  read("common.img_topic", node.img_topic);
  read("vio.normal_en", config.normal_en);
  read("vio.inverse_composition_en", config.inverse_composition_en);
  read("vio.max_iterations", config.max_iterations);
  read("vio.img_point_cov", config.IMG_POINT_COV);
  read("vio.raycast_en", config.raycast_en);
  read("vio.exposure_estimate_en", config.exposure_estimate_en);
  read("vio.inv_expo_cov", config.inv_expo_cov);
  read("vio.grid_size", config.grid_size);
  read("vio.grid_n_height", config.grid_n_height);
  read("vio.patch_pyrimid_level", config.patch_pyrimid_level);
  read("vio.patch_size", config.patch_size);
  read("vio.outlier_threshold", config.outlier_threshold);
  read("time_offset.exposure_time_init", config.exposure_time_init);
  read("time_offset.img_time_offset", config.img_time_offset);
  read("time_offset.imu_time_offset", config.imu_time_offset);
  read("time_offset.lidar_time_offset", config.lidar_time_offset);
  read("uav.imu_rate_odom", config.imu_prop_enable);
  read("uav.gravity_align_en", config.gravity_align_en);
  read("evo.seq_name", config.seq_name);
  read("evo.pose_output_en", config.pose_output_en);
  read("imu.gyr_cov", config.gyr_cov);
  read("imu.acc_cov", config.acc_cov);
  read("imu.imu_int_frame", config.imu_int_frame);
  read("imu.imu_en", config.imu_en);
  read("imu.gravity_est_en", config.gravity_est_en);
  read("imu.ba_bg_est_en", config.ba_bg_est_en);
  read("preprocess.blind", config.blind);
  read("preprocess.filter_size_surf", config.filter_size_surf_min);
  read("preprocess.hilti_en", config.hilti_en);
  read("preprocess.lidar_type", config.lidar_type);
  read("preprocess.scan_line", config.N_SCANS);
  read("preprocess.point_filter_num", config.point_filter_num);
  read("preprocess.feature_extract_enabled", config.feature_enabled);
  read("pcd_save.interval", config.pcd_save_interval);
  read("pcd_save.pcd_save_en", config.pcd_save_en);
  read("pcd_save.type", config.pcd_save_type);
  read("image_save.img_save_en", config.img_save_en);
  read("image_save.interval", config.img_save_interval);
  read("pcd_save.colmap_output_en", config.colmap_output_en);
  read("pcd_save.filter_size_pcd", config.filter_size_pcd);
  read("extrin_calib.extrinsic_T", config.extrinT);
  read("extrin_calib.extrinsic_R", config.extrinR);
  read("extrin_calib.Pcl", config.cameraextrinT);
  read("extrin_calib.Rcl", config.cameraextrinR);
  read("debug.plot_time", config.plot_time);
  read("debug.frame_cnt", config.frame_cnt);
  read("publish.blind_rgb_points", config.blind_rgb_points);
  read("publish.pub_scan_num", config.pub_scan_num);
  read("publish.pub_effect_point_en", config.pub_effect_point_en);
  read("publish.dense_map_en", config.dense_map_en);
  read("publish.pub_plane_en", config.geometry.is_pub_plane_map_);
  read("lio.max_layer", config.geometry.max_layer_);
  read("lio.voxel_size", config.geometry.max_voxel_size_);
  read("lio.min_eigen_value", config.geometry.planner_threshold_);
  read("lio.sigma_num", config.geometry.sigma_num_);
  read("lio.beam_err", config.geometry.beam_err_);
  read("lio.dept_err", config.geometry.dept_err_);
  read("lio.layer_init_num", config.geometry.layer_init_num_);
  read("lio.max_points_num", config.geometry.max_points_num_);
  read("lio.max_iterations", config.geometry.max_iterations_);
  read("local_map.map_sliding_en", config.geometry.map_sliding_en);
  read("local_map.half_map_size", config.geometry.half_map_size);
  read("local_map.sliding_thresh", config.geometry.sliding_thresh);
  read("common.num_threads", config.num_threads);
  read("debug.runtime_log_en", config.runtime_log_en);
  read("output_directory", config.output_directory);
  read("common.world_frame", node.world_frame);
  read("common.body_frame", node.body_frame);
  camera_read("cam_model", config.camera.model);
  camera_read("cam_calib_file", config.camera.calibration_file);
  camera_read("cam_width", config.camera.width);
  camera_read("cam_height", config.camera.height);
  camera_read("scale", config.camera.scale);
  camera_read("cam_fx", config.camera.fx);
  camera_read("cam_fy", config.camera.fy);
  camera_read("cam_cx", config.camera.cx);
  camera_read("cam_cy", config.camera.cy);
  camera_read("cam_skew", config.camera.skew);
  camera_read("cam_d0", config.camera.d0);
  camera_read("cam_d1", config.camera.d1);
  camera_read("cam_d2", config.camera.d2);
  camera_read("cam_d3", config.camera.d3);
  camera_read("k1", config.camera.k1);
  camera_read("k2", config.camera.k2);
  camera_read("k3", config.camera.k3);
  camera_read("k4", config.camera.k4);
  camera_read("k5", config.camera.k5);
  camera_read("k6", config.camera.k6);
  camera_read("k7", config.camera.k7);
  return node;
}
} // namespace fast_livo2::adapter
